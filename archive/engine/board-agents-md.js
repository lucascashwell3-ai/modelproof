/* Retired AGENTS.md builders (archived verbatim from board.html).
   "Copy AGENTS.md" printed one markdown file per mode; the personal file routed tasks through the
   retired engine. The board now exports the instruction package from assets/instructions.mjs
   (buildPackage + renderPreview), the same generator the installer uses.
   These fragments ran inside board.html's IIFE and are not runnable on their own. */

  /* ---------------- AGENTS.md, one file per mode (item 3) ----------------
     Org mode writes a policy file: who is on what, what it costs, whether it clears the data
     rule, and what changed this session. Personal mode writes a routing file driven by the Role
     blocks on the board. Nothing prints a literal null — an unset field reads "not set". */
  function mdModelLabel(b){
    var ids = blockModelIds(b).filter(Boolean);
    if (!ids.length) return b.modelRaw ? (b.modelRaw + " (not in our data yet)") : "not set";
    return ids.map(function(id){ var m = modelById(id); return m ? (m.name + " [" + id + ", " + m.vendor + "]") : id; }).join(" + ");
  }
  /* Contract item 5: the file says the same thing the panel says - the arithmetic, then where
     each number came from. A block with both a seat line and a token line prints both. */
  function mdCostLine(b, indent){
    var pad = indent || "  ";
    var ls = costLines(b), out = [];
    ls.forEach(function(l, i){
      var head = (i === 0 ? "" : pad + "  ");
      if (NO_AMOUNT_LINE[l.kind]){ out.push(head + l.math.replace(/\u201c|\u201d/g, '"').replace(/\u00d7/g, "x")); return; }
      out.push(head + l.math.replace(/\u00d7/g, "x") + " = " + fmtUsd(l.amount) + "/mo");
      if (l.note) out.push(pad + "  - " + l.note);
      if (l.src) out.push(pad + "  - " + l.src);
    });
    if (ls.length > 1) out.push(pad + "  - total: " + fmtUsd(costOfBlock(b)) + "/mo");
    var first = out.shift();
    return first + (out.length ? ("\n" + out.join("\n")) : "");
  }
  function mdNameList(ids){
    var names = ids.map(function(id){ var m = modelById(id); return m ? m.name : id; }).filter(Boolean);
    return names.length ? names.join(", ") : "";
  }
  function buildOrgPolicyMd(){
    var f = state.startFilters || {};
    var rule = currentDataRule();
    var lines = [];
    lines.push("# AGENTS.md — " + (state.boardName || "Untitled board") + " model policy");
    lines.push("");
    lines.push("Generated by Modelproof from your org board. Prices, tags and vendor countries come from the board's own data.");
    lines.push("");
    lines.push("## Overview");
    lines.push("- Org: " + (state.boardName || "not set"));
    var boardHeads = headcountOfAll(state.org.blocks);
    var boardMoney = moneyThreeWays(computeOrgTotal(), boardHeads);
    lines.push("- Monthly total: " + boardMoney.month + " across " + state.org.blocks.length + " block" + (state.org.blocks.length===1?"":"s") + " in " + state.org.divisions.length + " division" + (state.org.divisions.length===1?"":"s"));
    lines.push("- Per person: " + (boardMoney.person ? (boardMoney.person + "/mo across " + boardHeads + " " + (boardHeads === 1 ? "person" : "people") + " (routines carry no seats)") : "no seats on this board"));
    lines.push("- Per year: " + boardMoney.year);
    lines.push("- Data rule: " + ruleTipText(rule));
    lines.push("- Stance: " + (f.stance ? STANCE_LABELS[f.stance] : "not set"));
    lines.push("- Labs already paid for: " + ((f.labs && f.labs.length) ? f.labs.join(", ") : "not set"));
    lines.push("- Never suggest: " + (state.neverSuggest.length ? mdNameList(state.neverSuggest) : "nothing excluded"));
    lines.push("");
    lines.push("## Divisions");
    if (!state.org.blocks.length && !state.org.divisions.length){
      lines.push("- Nothing on the board yet.");
    }
    var groups = state.org.divisions.map(function(d){
      return { division: d, name: d.name || "not set", members: state.org.blocks.filter(function(b){ return b.divisionId === d.id; }) };
    });
    var loose = state.org.blocks.filter(function(b){ return !b.divisionId; });
    if (loose.length) groups.push({ division: null, name: "Not in a division", members: loose });

    // Item 3: a routine is named under every block it serves, and says who else it is shared
    // with, so a reader of one team's entry never has to hunt for the jobs running against it.
    function mdServedByLines(b, pad){
      return routinesServing(b.id).map(function(r){
        var others = servedBlocksOf(r).filter(function(x){ return x.id !== b.id; }).map(function(x){ return x.who; });
        return pad + "- routine: " + (r.who || "not set") + (others.length ? (" — shared with " + others.join(", ")) : "");
      });
    }
    function mdBlockEntry(b, note, pad){
      pad = pad || "";
      var kind = b.type === "person" ? "person" : b.type === "team" ? "team" : "routine";
      var breach = blockBreach(b);
      lines.push(pad + "- " + (b.who || "not set") + " (" + kind + ")" + (note ? (" — " + note) : ""));
      lines.push(pad + "  - task: " + (b.task ? taskLabel(b.task) : "not set"));
      lines.push(pad + "  - model: " + mdModelLabel(b));
      lines.push(pad + "  - plans: " + (planListOf(b).length ? planListOf(b).join(" + ") : (b.calls_per_day > 0 ? "none (billed per call)" : "not set")));
      // Item 5: the team first, then the people inside it who are on something else.
      teamRows(b).forEach(function(r){
        lines.push(pad + "    - " + (r.label || "row") + " x" + Math.max(0, r.seats || 0) + ": " + (mdNameList(rowModelIds(r)) || "no model"));
      });
      if (teamRows(b).length) lines.push(pad + "    - everyone else x" + remainderSeats(b) + ": " + (mdNameList(knownModelIds(b)) || "no model"));
      if (b.type === "routine"){
        var serves = servedBlocksOf(b).map(function(x){ return x.who; });
        lines.push(pad + "  - serves: " + (serves.length ? serves.join(", ") : "nobody yet"));
        lines.push(pad + "  - counted once, here — however many teams it serves");
      }
      lines.push(pad + "  - monthly cost: " + mdCostLine(b, pad + "  "));
      lines.push(pad + "  - data rule: " + (breach ? ("BREAKS " + RULE_LABELS[rule] + " — " + breach) : ("clears " + RULE_LABELS[rule])));
      mdServedByLines(b, pad + "  ").forEach(function(l){ lines.push(l); });
    }

    groups.forEach(function(g){
      var sub = g.members.reduce(function(s,b){ return s + costOfBlock(b); }, 0);
      var heads = headcountOfAll(g.members);
      var money = moneyThreeWays(sub, heads);
      lines.push("");
      // Item 1: the division's money said three ways, exactly as the board's own header says it.
      lines.push("### " + g.name + " — " + money.month + "/mo" +
        (money.person ? (" · " + money.person + "/person/mo") : "") +
        " · " + money.year + "/yr, " + g.members.length + " block" + (g.members.length===1?"":"s"));
      if (!g.members.length){ lines.push("- Empty."); return; }
      var d = g.division;
      var hasDefault = !!(d && d.defaultModel);
      // Item 6: the default first, then only the blocks that differ from it, then the routines.
      if (hasDefault){
        var dm = modelById(d.defaultModel);
        lines.push("- Division default: " + (dm ? (dm.name + " [" + dm.id + ", " + dm.vendor + "]") : d.defaultModel) +
          " · plans: " + ((d.defaultPlans || []).length ? d.defaultPlans.join(" + ") : "none"));
      }
      var staff = g.members.filter(function(b){ return b.type !== "routine"; });
      var routines = g.members.filter(function(b){ return b.type === "routine"; });
      var differs = hasDefault ? staff.filter(function(b){ return blockDiffersFromDivision(b, d); }) : staff;
      var onDefault = hasDefault ? staff.filter(function(b){ return !blockDiffersFromDivision(b, d); }) : [];
      differs.forEach(function(b){ mdBlockEntry(b, hasDefault ? "differs from the division default" : null); });
      if (onDefault.length){
        lines.push("- On the division default (" + onDefault.length + "): every field above, their own headcount and cost:");
        onDefault.forEach(function(b){
          lines.push("  - " + (b.who || "not set") + " (" + (b.type === "team" ? "team" : "person") + "): " + mdCostLine(b, "    "));
          mdServedByLines(b, "    ").forEach(function(l){ lines.push(l); });
        });
      }
      if (routines.length){
        lines.push("- Routines");
        routines.forEach(function(b){ mdBlockEntry(b, null, "  "); });
      }
    });
    lines.push("");
    lines.push("## Changes applied");
    if (!state.applyLog.length){
      lines.push("- None applied in this session.");
    } else {
      state.applyLog.forEach(function(a){
        lines.push("- " + a.who + ": " + a.from + " -> " + a.to + (a.plan ? (" on " + a.plan) : "") + " — " + saveLabel(a.save));
      });
    }
    lines.push("");
    lines.push("## How we pick");
    lines.push("- The shortlist, the filters, the evidence behind each pick and what we never do: ./how-we-pick.html");
    return lines.join("\n");
  }
  function buildPersonalAgentsMd(){
    var p = state.personal;
    var mePlans = planListOf(p.me);
    var tier = p.me.optimizeFor;
    var lines = [];
    lines.push("# AGENTS.md");
    lines.push("");
    lines.push("Generated by Modelproof from your personal board. The Role blocks on that board are the routing.");
    lines.push("");
    lines.push("## Plan");
    lines.push("- Plans: " + (mePlans.length ? mePlans.join(" + ") : "not set") + (mePlans.length ? " (" + fmtUsd2(planSeatPrice(mePlans)) + "/mo)" : ""));
    lines.push("- Monthly cost: " + mdCostLine(meCostBlock(), ""));
    lines.push("- Optimizing for " + tier + ": " + OPTIMIZE_COPY[tier]);
    lines.push("- Models you use: " + (p.me.uses.length ? mdNameList(p.me.uses) : "not set"));
    lines.push("");
    lines.push("## Never suggest");
    if (!state.neverSuggest.length){
      lines.push("- Nothing excluded.");
    } else {
      state.neverSuggest.forEach(function(id){
        var m = modelById(id);
        lines.push("- " + (m ? m.name + " [" + id + "]" : id) + ": never propose it and never pick it automatically, even when it is cheaper. A role you attached it to yourself stays as you set it.");
      });
    }
    lines.push("");
    lines.push("## Roles");
    if (!p.roles.length){
      lines.push("- No roles on the board yet, so there is nothing to route. Add a Role and attach a model to it.");
    } else {
      p.roles.forEach(function(r){
        var m = r.model ? modelById(r.model) : null;
        var breach = r.model ? dataRuleBreach(r.model) : null;
        lines.push("- " + (r.role || "not set") + ": " + (m ? (m.name + " at " + (r.effort || tierEffort(tier)) + " effort") : "no model attached yet") +
          (breach ? (" — breaks your data rule: " + breach) : "") +
          (isExcluded(r.model) ? " — on your never-suggest list; kept because you attached it" : ""));
      });
    }
    lines.push("");
    lines.push("Task routing that follows from those roles:");
    p.taskDefs.forEach(function(def){
      var row = computePersonalTaskRow(def, tier, mePlans);
      if (row.notMeasured){
        lines.push("- " + row.label + ": not measured — " + row.reason.replace(/^.*Not measured — /, ""));
      } else {
        var why = row.roleName ? ("your \u201c" + row.roleName + "\u201d role")
          : (/never-suggest/.test(row.reason) ? "the role for this has a never-suggest model attached, so this is the " + tier + " pick"
                                             : "no role set for this yet, so this is the " + tier + " pick");
        lines.push("- " + row.label + ": " + modelById(row.model).name + " at " + row.effort + " effort — " + why);
      }
    });
    lines.push("");
    lines.push("## Delegation");
    var byKind = {};
    p.roles.forEach(function(r){ var k = roleKind(r.role); if (k && r.model && !byKind[k]) byKind[k] = r; });
    var coord = byKind["coordinator"];
    var downstream = ["long-haul code", "bulk", "research", "design"];
    if (coord){
      var handed = 0;
      downstream.forEach(function(k){
        var r = byKind[k];
        if (!r) return;
        handed++;
        var m = modelById(r.model);
        if (r.model === coord.model){ lines.push("- " + coord.role + " does " + k + " work itself (" + r.role + " is on the same model, " + (m ? m.name : "not set") + ")."); return; }
        lines.push("- " + coord.role + " hands " + k + " work to " + r.role + " (" + (m ? m.name : "not set") + (isExcluded(r.model) ? ", on your never-suggest list" : "") + ").");
      });
      if (!handed) lines.push("- " + coord.role + " has nowhere to hand off yet — no long-haul code, bulk, research or design role on the board.");
    } else {
      lines.push("- No coordinator role on the board yet, so hand-offs are not defined. Add one to say who routes work to whom.");
    }
    lines.push("- Never spend the coordinator's context on bulk reading: hand that to the bulk role and take back the summary.");
    lines.push("");
    lines.push("## Effort");
    if (mePlans.some(function(n){ return planVendorOf(n) === "Anthropic"; })){
      lines.push("- Anthropic documents the effort levels its models accept: https://platform.claude.com/docs");
    }
    lines.push("- Where a role sets no effort of its own, use " + tierEffort(tier) + " — the level that matches the " + tier + " stance above.");
    lines.push("- Raise effort for a task that failed at a lower one; don't start at the top by default.");
    lines.push("");
    lines.push("## Context hygiene");
    lines.push("- Keep CLAUDE.md short: standing facts only, not instructions that change every week.");
    lines.push("- Put routing in this AGENTS.md: which role, which model, which effort.");
    lines.push("- Delegate big reads to the bulk role and keep only its answer in the main thread.");
    lines.push("- One thread at a time: finish a task before starting the next one in the same context.");
    lines.push("- Verify with real output — a test run, a diff, a screenshot — before calling anything done.");
    lines.push("");
    lines.push("## How we pick");
    lines.push("- The shortlist, the filters, the evidence behind each pick and what we never do: ./how-we-pick.html");
    return lines.join("\n");
  }
  function buildAgentsMd(){ return mode === "org" ? buildOrgPolicyMd() : buildPersonalAgentsMd(); }
  var agentsTextarea = document.getElementById("agentsMdText");
  document.getElementById("bpCopyAgents").addEventListener("click", function(){
    var text = buildAgentsMd();
    agentsTextarea.value = text;
    var done = function(){ showToast(mode === "org" ? "Org policy AGENTS.md copied" : "Personal AGENTS.md copied"); };
    if (navigator.clipboard && navigator.clipboard.writeText){
      navigator.clipboard.writeText(text).then(done).catch(function(){
        agentsTextarea.hidden = false; agentsTextarea.select(); document.execCommand("copy"); agentsTextarea.hidden = true; done();
      });
    } else {
      agentsTextarea.hidden = false; agentsTextarea.select(); document.execCommand("copy"); agentsTextarea.hidden = true; done();
    }
  });


/* ---- debug hook ---- */
  window.__mpAgentsMd = function(){ return buildAgentsMd(); };
